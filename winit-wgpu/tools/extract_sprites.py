def write_sprite(name, grid, palette_key):
    palette = PALETTES[palette_key]
    lines = []
    for idx, hex_color in sorted(palette.items()):
        lines.append(f'{idx} {hex_color}')
    lines.append('')
    for row in grid:
        lines.append(''.join(str(c) for c in row))
    path = os.path.join(OUT_DIR, f'{name}.sprite')
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'wrote {path}')


if __name__ == '__main__':
    os.makedirs(OUT_DIR, exist_ok=True)
    for name, grid, palette_key in SPRITES:
        write_sprite(name, grid, palette_key)
    print(f'done — {len(SPRITES)} sprites written')
